/* =========================================================
   HELPERS
   ========================================================= */

function cleanString(value) {

  if (
    typeof value !== "string"
  ) {

    return "";

  }


  return value.trim();

}


/* =========================================================
   CLEAN QUESTION TYPE
   ========================================================= */

function cleanQuestionType(value) {

  if (
    typeof value !== "string"
  ) {

    return "other";

  }


  if (
    Object.prototype.hasOwnProperty.call(
      QUESTION_TYPES,
      value
    )
  ) {

    return value;

  }


  return "other";

}


/* =========================================================
   CLEAN STRUCTURED BLOCKS
   ========================================================= */

function cleanStructuredBlocks(blocks) {

  if (
    !Array.isArray(blocks)
  ) {

    return [];

  }


  const cleanBlocks = [];


  for (
    const block of blocks
  ) {

    if (
      !block ||
      typeof block !== "object"
    ) {

      continue;

    }


    /* =====================================================
       HEADING
       ===================================================== */

    if (
      block.type === "heading"
    ) {

      const content =
        cleanString(
          block.content
        );


      if (content) {

        cleanBlocks.push({

          type: "heading",

          content: content

        });

      }


      continue;

    }


    /* =====================================================
       MATH
       ===================================================== */

    if (
      block.type === "math"
    ) {

      const content =
        cleanString(
          block.content
        );


      if (content) {

        cleanBlocks.push({

          type: "math",

          content: content

        });

      }


      continue;

    }


    /* =====================================================
       PARAGRAPH
       ===================================================== */

    if (
      block.type === "paragraph" &&
      Array.isArray(
        block.segments
      )
    ) {

      const cleanSegments = [];


      for (
        const segment of block.segments
      ) {

        if (
          !segment ||
          typeof segment !== "object"
        ) {

          continue;

        }


        if (
          segment.type !== "text" &&
          segment.type !== "inline_math"
        ) {

          continue;

        }


        const content =
          cleanString(
            segment.content
          );


        if (!content) {

          continue;

        }


        cleanSegments.push({

          type:
            segment.type,

          content:
            content

        });

      }


      if (
        cleanSegments.length > 0
      ) {

        cleanBlocks.push({

          type: "paragraph",

          segments:
            cleanSegments

        });

      }

    }

  }


  return cleanBlocks;

}


/* =========================================================
   POST /ask
   ========================================================= */

app.post(
  "/ask",
  async (req, res) => {

    try {

      const {
        question,
        image
      } = req.body || {};


      /* =====================================================
         VALIDATION
         ===================================================== */

      const cleanQuestion =
        typeof question === "string"
          ? question.trim()
          : "";


      if (
        !cleanQuestion &&
        !image
      ) {

        return res
          .status(400)
          .json({
            error:
              "اكتب سؤالاً أو اختر صورة أولاً."
          });

      }


      if (
        !process.env.OPENAI_API_KEY
      ) {

        return res
          .status(500)
          .json({
            error:
              "مفتاح OpenAI غير موجود في إعدادات الخادم."
          });

      }


      /* =====================================================
         BUILD INPUT
         ===================================================== */

      const content = [];


      const prompt =
        buildStudyPrompt(
          cleanQuestion,
          Boolean(image)
        );


      content.push({

        type: "input_text",

        text: prompt

      });


      /* =====================================================
         IMAGE
         ===================================================== */

      if (image) {

        content.push({

          type: "input_image",

          image_url: image

        });

      }


      /* =====================================================
         OPENAI
         ===================================================== */

      const response =
        await openai.responses.create({

          model:
            "gpt-5-mini",

          input: [

            {

              role: "user",

              content:
                content

            }

          ],


          /* =================================================
             STRUCTURED OUTPUT
             ================================================= */

          text: {

            format: {

              type:
                "json_schema",

              name:
                "study_answer_v3_2",

              strict:
                true,

              schema:
                studyAnswerSchema

            }

          }

        });


      /* =====================================================
         OUTPUT TEXT
         ===================================================== */

      const outputText =
        response.output_text;


      if (
        !outputText ||
        !outputText.trim()
      ) {

        return res
          .status(500)
          .json({
            error:
              "تمت معالجة السؤال ولكن لم تصل إجابة منظمة."
          });

      }


      /* =====================================================
         PARSE
         ===================================================== */

      let structuredAnswer;


      try {

        structuredAnswer =
          JSON.parse(
            outputText
          );

      } catch (parseError) {

        console.error(
          "STRUCTURED OUTPUT PARSE ERROR:",
          parseError
        );


        console.error(
          "RAW OUTPUT:",
          outputText
        );


        return res
          .status(500)
          .json({
            error:
              "تعذر قراءة الإجابة المنظمة من النموذج."
          });

      }


      /* =====================================================
         STRUCTURE CHECK
         ===================================================== */

      if (
        !structuredAnswer ||
        !Array.isArray(
          structuredAnswer.blocks
        )
      ) {

        return res
          .status(500)
          .json({
            error:
              "الإجابة المنظمة لا تحتوي على blocks صحيحة."
          });

      }


      /* =====================================================
         QUESTION TYPE
         ===================================================== */

      const questionType =
        cleanQuestionType(
          structuredAnswer.question_type
        );


      const questionTypeLabel =
        QUESTION_TYPES[
          questionType
        ];


      /* =====================================================
         CLEAN BLOCKS
         ===================================================== */

      const cleanBlocks =
        cleanStructuredBlocks(
          structuredAnswer.blocks
        );


      if (
        cleanBlocks.length === 0
      ) {

        return res
          .status(500)
          .json({
            error:
              "وصلت إجابة ولكنها لا تحتوي على محتوى صالح للعرض."
          });

      }


      /* =====================================================
         SERVER LOG
         ===================================================== */

      console.log(
        "QUESTION TYPE:",
        questionType,
        "-",
        questionTypeLabel
      );


      /* =====================================================
         SEND RESPONSE

         Keep version: 2 intentionally.
         The current frontend remains fully compatible.
         ===================================================== */

      return res.json({

        version: 2,

        question_type:
          questionType,

        question_type_label:
          questionTypeLabel,

        blocks:
          cleanBlocks

      });


    } catch (error) {

      console.error(
        "OPENAI ERROR:",
        error
      );


      const message =

        error?.error?.message ||

        error?.message ||

        "حدث خطأ غير معروف أثناء معالجة السؤال.";


      return res
        .status(500)
        .json({
          error:
            message
        });

    }

  }
);


