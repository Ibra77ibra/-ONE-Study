const express = require("express");
const OpenAI = require("openai");

const app = express();

app.use(
  express.json({
    limit: "20mb"
  })
);

app.use(express.static("public"));

const openai = new OpenAI({
  apiKey: process.env.OPENAI_API_KEY
});

app.post("/ask", async (req, res) => {
  try {
    const { question, image } = req.body || {};

    if (!question && !image) {
      return res.status(400).json({
        error: "اكتب سؤالاً أو اختر صورة أولاً."
      });
    }

    if (!process.env.OPENAI_API_KEY) {
      return res.status(500).json({
        error: "مفتاح OpenAI غير موجود في إعدادات الخادم."
      });
    }

    const content = [];

    const instructions = `
أنت مساعد دراسي ذكي للطلاب.

مهمتك هي قراءة السؤال المكتوب أو الصورة الدراسية بدقة ثم تقديم الحل الصحيح والواضح.

قواعد مهمة جداً:

1. إذا كانت هناك صورة، افحص الصورة كاملة بعناية قبل الإجابة.

2. استخرج جميع الأسئلة الظاهرة بوضوح في الصورة، وليس سؤالاً واحداً فقط.

3. حافظ على أرقام الأسئلة الأصلية كما تظهر في الصورة.
مثال:
11) ...
12) ...
13) ...

4. لا تحل أي سؤال غير ظاهر بوضوح في الصورة.

5. لا تخترع نصاً أو أرقاماً أو معلومات غير موجودة.

6. إذا كان جزء من السؤال مقطوعاً أو غير مقروء، اذكر أنه غير واضح بدلاً من التخمين.

7. إذا احتوت الصورة على عمودين أو أكثر من الأسئلة، افحص جميع الأعمدة.

8. إذا كانت الصفحة تحتوي على أقسام مثل:
Part A
Part B
Reflect
Fluency Check
أو غيرها،
حافظ على ترتيب الأقسام والأسئلة.

9. في مسائل الرياضيات:
- احسب النتيجة بدقة.
- حافظ على ترتيب الأرقام والرموز الرياضية.
- استخدم علامة = بطريقة واضحة.
- لا تعكس الأرقام بسبب اتجاه اللغة العربية.

10. المسائل الحسابية البسيطة مثل:
5 × 10
6 × 10
2 × 5
تعرض بشكل مختصر:
11) 5 × 10 = 50

ولا تكتب شرحاً طويلاً لعملية حسابية بسيطة إلا إذا كان السؤال يطلب شرح الطريقة.

11. إذا كانت المسألة تحتاج خطوات فعلية، اعرض:
السؤال
الحل
الخطوات
النتيجة النهائية

12. إذا كانت هناك عدة أسئلة في الصورة، افصل كل سؤال عن الآخر بوضوح.

13. أجب باللغة المناسبة لمحتوى السؤال:
- السؤال العربي: بالعربية.
- السؤال الإنجليزي: يمكن شرح الحل بالعربية مع المحافظة على المصطلحات الإنجليزية المهمة.
- الرياضيات: حافظ على الرموز والأرقام بصورتها الرياضية الطبيعية.

14. لا تكرر السؤال أو النتيجة بلا حاجة.

15. اجعل الإجابة مناسبة لطالب: صحيحة، واضحة، مباشرة، ومنظمة.

16. لا تضف عبارات جانبية مثل:
"إذا أردت أستطيع..."
أو اقتراحات إضافية بعد الحل.

17. عند وجود صورة فقط، اعتبر المطلوب تلقائياً:
"اقرأ جميع الأسئلة الظاهرة بوضوح في الصورة وحلها جميعاً بالترتيب."

18. إذا كانت الصورة تحتوي على جزء فقط من صفحة، حل فقط الأسئلة التي يظهر نصها كاملاً بما يكفي للحل.
`;

    content.push({
      type: "input_text",
      text: question
        ? `${instructions}

السؤال المكتوب من الطالب:
${question}`
        : instructions
    });

    if (image) {
      content.push({
        type: "input_image",
        image_url: image
      });
    }

    const response = await openai.responses.create({
      model: "gpt-5-mini",
      input: [
        {
          role: "user",
          content: content
        }
      ]
    });

    const answer =
      response.output_text ||
      "تمت معالجة السؤال ولكن لم تصل إجابة نصية.";

    return res.json({
      answer: answer
    });
  } catch (error) {
    console.error("OPENAI ERROR:", error);

    const message =
      error?.error?.message ||
      error?.message ||
      "حدث خطأ غير معروف أثناء معالجة السؤال.";

    return res.status(500).json({
      error: message
    });
  }
});

const PORT = process.env.PORT || 3000;

app.listen(PORT, () => {
  console.log(`ONE Study server running on port ${PORT}`);
});
