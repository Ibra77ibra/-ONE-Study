const express = require("express");
const OpenAI = require("openai");

const app = express();


/* =========================================================
   EXPRESS
   ========================================================= */

app.use(
  express.json({
    limit: "30mb"
  })
);

app.use(
  express.static("public")
);


/* =========================================================
   OPENAI
   ========================================================= */

const openai = new OpenAI({
  apiKey: process.env.OPENAI_API_KEY
});


/* =========================================================
   STUDY PROMPT
   ========================================================= */

function buildStudyPrompt(question, hasImage) {

  return `
أنت مساعد دراسي عربي متخصص في قراءة وشرح وحل الأسئلة التعليمية للطلاب.

مهمتك:
اقرأ السؤال بعناية، وافهم المطلوب كاملاً، ثم قدم حلاً صحيحاً ومنظماً وواضحاً باللغة العربية.

==================================================
قراءة السؤال
==================================================

${hasImage
  ? `
هناك صورة مرفقة تحتوي على سؤال دراسي.

يجب عليك:
- قراءة الصورة بعناية.
- استخراج جميع المعلومات المطلوبة منها.
- قراءة الرموز والأرقام والمعادلات بدقة.
- إذا احتوت الصورة على أكثر من سؤال أو جزء، أجب عن جميع الأجزاء.
- لا تتجاهل أي شرط ظاهر في الصورة.
- لا تخترع معلومات غير موجودة.
- إذا كان جزء أساسي غير واضح فعلاً، وضح ذلك بدلاً من التخمين.
`
  : `
لا توجد صورة مرفقة.
اعتمد على السؤال النصي الذي كتبه الطالب.
`
}

${question
  ? `
==================================================
سؤال الطالب
==================================================

${question}
`
  : ""
}

==================================================
طريقة الحل
==================================================

اكتب حلاً تعليمياً واضحاً باللغة العربية.

اشرح الخطوات الأساسية بترتيب منطقي.

لا تختصر خطوة ضرورية لفهم الحل.

لا تكرر المعلومات أو النتائج دون حاجة.

إذا كان السؤال متعدد الأجزاء، أجب عن جميع الأجزاء.

راجع العمليات الحسابية والنتيجة قبل إرسال الإجابة.

==================================================
بنية الإجابة
==================================================

الإجابة ستُعاد في صورة مجموعة blocks منظمة.

كل block يجب أن يكون واحداً من الأنواع التالية فقط:

heading
text
math

استخدم:

heading
للعناوين فقط، مثل:
الحل
النتيجة النهائية

استخدم:

text
للشرح العربي فقط.

استخدم:

math
لأي معادلة أو تعبير رياضي مستقل.

==================================================
قواعد مهمة جداً للرياضيات
==================================================

كل block من النوع math يجب أن يحتوي على LaTeX خام فقط.

لا تستخدم:

\$begin:math:display$
\\$end:math:display$

ولا تستخدم:

\$begin:math:text$
\\$end:math:text$

ولا تستخدم:

$

ولا تستخدم:

$$

ولا تستخدم:

begin:math

ولا تستخدم Markdown.

مثال صحيح لمحتوى math:

f'(x)=3x^2-12x+9

مثال صحيح آخر:

a=2\\pm\\sqrt{2}

مثال صحيح:

\\frac{4\\pm\\sqrt{16-8}}{2}

==================================================
كتابة LaTeX
==================================================

استخدم:

x^2

للأس.

استخدم:

a_1

للرمز السفلي.

استخدم:

\\sqrt{2}

للجذر.

استخدم:

\\frac{a}{b}

للكسر.

استخدم:

\\pm

للزائد أو الناقص.

استخدم:

\\times

للضرب عند الحاجة.

استخدم:

\\Rightarrow

للاستنتاج عند الحاجة.

==================================================
منع التكرار
==================================================

هذه قاعدة إلزامية:

لا تكتب أي معادلة مرتين.

إذا وضعت المعادلة داخل block من النوع math، فلا تكتب نفس المعادلة داخل block من النوع text.

مثال:

text:
نحسب مشتقة الدالة:

math:
f'(x)=3x^2-12x+9

هذا صحيح.

أما كتابة المعادلة مرة أخرى داخل النص فممنوع.

==================================================
النص العربي والرياضيات
==================================================

يفضل أن يكون block من النوع text شرحاً عربياً طبيعياً.

إذا احتجت إلى معادلة مهمة، ضعها في block مستقل من النوع math.

مثال:

text:
بما أن المماس موازٍ للمستقيم المعطى، فإن ميل المماس يساوي ميل ذلك المستقيم.

math:
f'(a)=3

لا تضع جملة عربية كاملة داخل math.

==================================================
المعادلات الطويلة
==================================================

راعِ أن الطالب قد يستخدم شاشة هاتف.

لا تجمع سلسلة طويلة جداً من العمليات في block رياضي واحد.

بدلاً من:

3a^2-12a+9=3\\Rightarrow3a^2-12a+6=0\\Rightarrow a^2-4a+2=0

استخدم ثلاثة blocks من النوع math:

3a^2-12a+9=3

ثم:

3a^2-12a+6=0

ثم:

a^2-4a+2=0

==================================================
مسائل التفاضل والمماس
==================================================

إذا كان السؤال متعلقاً بالمشتقة أو المماس:

- حدد ميل المستقيم المعطى.
- احسب المشتقة بدقة.
- طبق شرط التوازي أو المماس.
- أوجد جميع القيم المطلوبة.
- لا تتوقف عند حل واحد إذا كان هناك أكثر من حل.
- عوض عن كل قيمة عند الحاجة.
- أوجد معادلة كل مماس.
- تحقق من النتائج.

==================================================
النتيجة النهائية
==================================================

في نهاية الحل استخدم block من النوع:

heading

ومحتواه:

النتيجة النهائية

ثم اذكر النتائج المطلوبة باستخدام text و math حسب الحاجة.

لا تكرر المعادلات النهائية بعد ذلك.

==================================================
الفحص النهائي
==================================================

قبل إرسال الإجابة تأكد من:

- الحل صحيح.
- جميع أجزاء السؤال تمت الإجابة عنها.
- لا توجد معادلات مكررة.
- كل معادلة مهمة موجودة في math فقط.
- math يحتوي على LaTeX خام فقط.
- لا توجد delimiters حول LaTeX.
- لا توجد Markdown code blocks.
- لا توجد كتابة مثل x2 بدلاً من x^2.
- لا توجد كتابة مثل sqrt(2) بدلاً من \\sqrt{2}.
- الجذور والكسور والأسس مكتوبة بطريقة صحيحة.
- لا توجد جملة عربية كاملة داخل math.
- المعادلات الطويلة مقسمة بما يناسب شاشة الهاتف.
`;

}


/* =========================================================
   STRUCTURED OUTPUT SCHEMA
   ========================================================= */

const studyAnswerSchema = {

  type: "object",

  properties: {

    blocks: {

      type: "array",

      items: {

        type: "object",

        properties: {

          type: {
            type: "string",
            enum: [
              "heading",
              "text",
              "math"
            ]
          },

          content: {
            type: "string"
          }

        },

        required: [
          "type",
          "content"
        ],

        additionalProperties: false

      }

    }

  },

  required: [
    "blocks"
  ],

  additionalProperties: false

};


/* =========================================================
   POST /ask
   ========================================================= */

app.post(
  "/ask",
  async (req, res) => {

    try {

      const {
        question,
        image
      } = req.body || {};


      /* =====================================================
         VALIDATION
         ===================================================== */

      const cleanQuestion =
        typeof question === "string"
          ? question.trim()
          : "";


      if (
        !cleanQuestion &&
        !image
      ) {

        return res
          .status(400)
          .json({
            error:
              "اكتب سؤالاً أو اختر صورة أولاً."
          });

      }


      if (
        !process.env.OPENAI_API_KEY
      ) {

        return res
          .status(500)
          .json({
            error:
              "مفتاح OpenAI غير موجود في إعدادات الخادم."
          });

      }


      /* =====================================================
         BUILD INPUT CONTENT
         ===================================================== */

      const content = [];


      const prompt =
        buildStudyPrompt(
          cleanQuestion,
          Boolean(image)
        );


      content.push({
        type: "input_text",
        text: prompt
      });


      /* =====================================================
         IMAGE
         ===================================================== */

      if (image) {

        content.push({
          type: "input_image",
          image_url: image
        });

      }


      /* =====================================================
         OPENAI RESPONSE
         STRUCTURED OUTPUT
         ===================================================== */

      const response =
        await openai.responses.create({

          model: "gpt-5-mini",

          input: [
            {
              role: "user",
              content: content
            }
          ],

          text: {

            format: {

              type: "json_schema",

              name: "study_answer",

              strict: true,

              schema: studyAnswerSchema

            }

          }

        });


      /* =====================================================
         GET STRUCTURED TEXT
         ===================================================== */

      const outputText =
        response.output_text;


      if (
        !outputText ||
        !outputText.trim()
      ) {

        return res
          .status(500)
          .json({
            error:
              "تمت معالجة السؤال ولكن لم تصل إجابة منظمة."
          });

      }


      /* =====================================================
         PARSE JSON
         ===================================================== */

      let structuredAnswer;


      try {

        structuredAnswer =
          JSON.parse(
            outputText
          );

      } catch (parseError) {

        console.error(
          "STRUCTURED OUTPUT PARSE ERROR:",
          parseError
        );

        console.error(
          "RAW OUTPUT:",
          outputText
        );


        return res
          .status(500)
          .json({
            error:
              "تعذر قراءة الإجابة المنظمة من النموذج."
          });

      }


      /* =====================================================
         VALIDATE BASIC STRUCTURE
         ===================================================== */

      if (
        !structuredAnswer ||
        !Array.isArray(
          structuredAnswer.blocks
        )
      ) {

        return res
          .status(500)
          .json({
            error:
              "الإجابة المنظمة لا تحتوي على blocks صحيحة."
          });

      }


      /* =====================================================
         CLEAN BLOCKS
         ===================================================== */

      const allowedTypes =
        new Set([
          "heading",
          "text",
          "math"
        ]);


      const cleanBlocks =
        structuredAnswer.blocks

          .filter(
            (block) =>
              block &&
              allowedTypes.has(
                block.type
              ) &&
              typeof block.content ===
                "string" &&
              block.content.trim()
          )

          .map(
            (block) => ({
              type:
                block.type,

              content:
                block.content.trim()
            })
          );


      if (
        cleanBlocks.length === 0
      ) {

        return res
          .status(500)
          .json({
            error:
              "وصلت إجابة ولكنها لا تحتوي على محتوى صالح للعرض."
          });

      }


      /* =====================================================
         SEND STRUCTURED ANSWER
         ===================================================== */

      return res.json({

        blocks:
          cleanBlocks

      });


    } catch (error) {

      console.error(
        "OPENAI ERROR:",
        error
      );


      const message =

        error?.error?.message ||

        error?.message ||

        "حدث خطأ غير معروف أثناء معالجة السؤال.";


      return res
        .status(500)
        .json({
          error:
            message
        });

    }

  }
);


/* =========================================================
   SERVER
   ========================================================= */

const PORT =
  process.env.PORT ||
  3000;


app.listen(
  PORT,
  () => {

    console.log(
      `ONE Study server running on port ${PORT}`
    );

  }
);
